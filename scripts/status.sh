#!/bin/bash
# ========================================
#   研发作业平台 - 状态检查
# ========================================

echo "========================================"
echo "   服务状态"
echo "========================================"
echo ""

echo "检查后端端口 8080 ..."
PID=$(lsof -ti:8080 2>/dev/null)
if [ -n "$PID" ]; then
    echo "  [后端] 运行中 - PID: $PID"
else
    echo "  [后端] 未运行"
fi

echo ""
echo "检查前端端口 3000 ..."
PID=$(lsof -ti:3000 2>/dev/null)
if [ -n "$PID" ]; then
    echo "  [前端] 运行中 - PID: $PID"
else
    echo "  [前端] 未运行"
fi

echo ""
echo "========================================"
echo "   后端: http://localhost:8080"
echo "   前端: http://localhost:3000"
echo "========================================"
