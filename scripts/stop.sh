#!/bin/bash
# ========================================
#   研发作业平台 - 停止脚本
# ========================================

echo "========================================"
echo "   停止前后端服务"
echo "========================================"
echo ""

echo "[1/2] 停止后端服务..."
PID=$(lsof -ti:8080 2>/dev/null)
if [ -n "$PID" ]; then
    echo "找到后端进程 PID: $PID"
    kill -9 $PID
    echo "后端进程已终止"
else
    echo "后端服务未运行"
fi

echo ""
echo "[2/2] 停止前端服务..."
PID=$(lsof -ti:3000 2>/dev/null)
if [ -n "$PID" ]; then
    echo "找到前端进程 PID: $PID"
    kill -9 $PID
    echo "前端进程已终止"
else
    echo "前端服务未运行"
fi

echo ""
echo "========================================"
echo "   停止完成！"
echo "========================================"
